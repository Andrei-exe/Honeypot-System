"""In-memory generators (zero disk writes) for CSV, JSON, firewall and SOC report exports."""

import csv
import io
import json
from collections import Counter
from datetime import datetime, timezone


def _utc_now():
    return datetime.now(timezone.utc).strftime("%Y-%m-%dT%H:%M:%SZ")


def alerts_to_csv(normalized_alerts):
    buf = io.StringIO()
    fields = [
        "timestamp",
        "severity",
        "score",
        "protocol",
        "source_ip",
        "source_port",
        "target_port",
        "node_id",
        "session_id",
        "event_type",
        "technique",
        "technique_name",
        "tactic",
        "alert_reason",
        "username",
        "password",
        "auth_success",
        "command",
        "http_method",
        "http_path",
        "http_user_agent",
        "extracted_url",
        "country",
        "city",
        "tags",
    ]
    writer = csv.DictWriter(buf, fieldnames=fields, extrasaction="ignore")
    writer.writeheader()

    for al in normalized_alerts:
        creds = al.get("credentials") or {}
        pd = al.get("payload_details") or {}
        geo = al.get("geo") or {}
        writer.writerow({
            "timestamp": al.get("timestamp", ""),
            "severity": al.get("severity", ""),
            "score": al.get("score", 0),
            "protocol": al.get("protocol", ""),
            "source_ip": al.get("source_ip", ""),
            "source_port": al.get("source_port") or "",
            "target_port": al.get("target_port") or "",
            "node_id": al.get("node_id", ""),
            "session_id": al.get("session_id", ""),
            "event_type": al.get("event_type", ""),
            "technique": al.get("technique") or "",
            "technique_name": al.get("technique_name") or "",
            "tactic": al.get("tactic") or "",
            "alert_reason": al.get("alert_reason", ""),
            "username": creds.get("username", ""),
            "password": creds.get("password", ""),
            "auth_success": creds.get("success", ""),
            "command": pd.get("command", ""),
            "http_method": pd.get("http_method", ""),
            "http_path": pd.get("http_path", ""),
            "http_user_agent": pd.get("http_user_agent", ""),
            "extracted_url": pd.get("extracted_url", ""),
            "country": geo.get("country", ""),
            "city": geo.get("city", ""),
            "tags": ";".join(al.get("tags") or []),
        })
    return buf.getvalue()


def sessions_to_csv(normalized_sessions):
    buf = io.StringIO()
    fields = [
        "session_id",
        "source_ip",
        "protocol",
        "kind",
        "node_id",
        "start",
        "end",
        "duration_label",
        "login_attempts",
        "successful_login",
        "command_count",
        "download_count",
        "stages",
        "family_labels",
        "max_severity",
        "risk_score",
        "tags",
    ]
    writer = csv.DictWriter(buf, fieldnames=fields, extrasaction="ignore")
    writer.writeheader()

    for s in normalized_sessions:
        writer.writerow({
            "session_id": s.get("session_id", ""),
            "source_ip": s.get("source_ip", ""),
            "protocol": s.get("protocol", ""),
            "kind": s.get("kind", ""),
            "node_id": s.get("node_id", ""),
            "start": s.get("start", ""),
            "end": s.get("end", ""),
            "duration_label": s.get("duration_label", ""),
            "login_attempts": s.get("login_attempts", 0),
            "successful_login": s.get("successful_login") or "",
            "command_count": len(s.get("commands") or []),
            "download_count": len(s.get("downloads") or []),
            "stages": " -> ".join(s.get("stages") or []),
            "family_labels": ";".join(s.get("family_labels") or []),
            "max_severity": s.get("max_severity", ""),
            "risk_score": s.get("risk_score", 0),
            "tags": ";".join(s.get("tags") or []),
        })
    return buf.getvalue()


def extract_ips_from_plain_blocklist(plain_text):
    ips = []
    for raw_line in (plain_text or "").splitlines():
        line = raw_line.strip()
        if not line or line.startswith("#"):
            continue
        token = line.split()[0]
        if token and token not in ips:
            ips.append(token)
    return ips


def build_iptables_script(ips):
    lines = [
        "#!/usr/bin/env bash",
        "# Generated by Honeypot SOC Dashboard at " + _utc_now(),
        f"# Total attacker IPs: {len(ips)}",
        "set -euo pipefail",
        "",
        "CHAIN=\"HONEYPOT_BLOCKLIST\"",
        "iptables -N \"$CHAIN\" 2>/dev/null || iptables -F \"$CHAIN\"",
        "iptables -C INPUT -j \"$CHAIN\" 2>/dev/null || iptables -I INPUT 1 -j \"$CHAIN\"",
        "",
    ]
    for ip in ips:
        lines.append(f"iptables -A \"$CHAIN\" -s {ip} -j DROP")
    if not ips:
        lines.append("# No attacker IPs currently eligible for blocking.")
    return "\n".join(lines) + "\n"


def build_ufw_script(ips):
    lines = [
        "#!/usr/bin/env bash",
        "# Generated by Honeypot SOC Dashboard at " + _utc_now(),
        f"# Total attacker IPs: {len(ips)}",
        "set -euo pipefail",
        "",
    ]
    for ip in ips:
        lines.append(f"ufw insert 1 deny from {ip} to any comment 'honeypot-blocklist'")
    if not ips:
        lines.append("# No attacker IPs currently eligible for blocking.")
    return "\n".join(lines) + "\n"


def build_incident_markdown(stats, sessions_health, normalized_alerts, campaigns, families, navigator):
    sev_counts = stats.get("alerts_by_severity") or {}
    proto_counts = stats.get("alerts_by_protocol") or {}
    top_ips = stats.get("top_ips") or []
    top_creds = stats.get("top_credentials") or []
    honeytokens = [a for a in normalized_alerts if a.get("honeytoken_hit")]
    techniques = (navigator or {}).get("techniques") or []

    rec_counter = Counter()
    for al in normalized_alerts:
        rec = (al.get("recommendation") or "").strip()
        if rec:
            rec_counter[rec] += 1

    lines = [
        "# HONEYPOT SOC // INCIDENT TELEMETRY REPORT",
        "",
        f"- **Generated (UTC):** `{_utc_now()}`",
        f"- **Observation Window:** `{stats.get('first_seen') or 'N/A'}` -> `{stats.get('last_seen') or 'N/A'}`",
        f"- **Total Events:** `{stats.get('total_events', 0)}`",
        f"- **Total Alerts:** `{stats.get('total_alerts', 0)}`",
        f"- **Unique Attacker IPs:** `{stats.get('unique_attacker_ips', 0)}`",
        f"- **SessionStore Load:** `{sessions_health.get('total_stored', 0)} / {sessions_health.get('capacity', 2000)}` (`{sessions_health.get('saturation_pct', 0)}%` - `{sessions_health.get('pressure', 'NOMINAL')}`)",
        "",
        "## 1. Severity & Protocol Breakdown",
        "",
        "| Severity | Count |",
        "| :--- | ---: |",
    ]
    for sev in ("CRITICAL", "HIGH", "MEDIUM", "LOW", "NONE"):
        lines.append(f"| {sev} | {sev_counts.get(sev, 0)} |")

    lines.extend([
        "",
        "| Protocol | Alerts |",
        "| :--- | ---: |",
    ])
    for proto, cnt in sorted(proto_counts.items(), key=lambda kv: kv[1], reverse=True):
        lines.append(f"| {proto} | {cnt} |")

    lines.extend([
        "",
        "## 2. Honeytoken Alerts",
        "",
    ])
    if honeytokens:
        for h in honeytokens[:20]:
            lines.append(f"- `{h.get('timestamp')}` | `{h.get('source_ip')}` | `{h.get('protocol')}` | {h.get('alert_reason')}")
    else:
        lines.append("- No honeytoken access recorded in the recent alert buffer.")

    lines.extend([
        "",
        "## 3. Top Attacker IPs",
        "",
        "| IP Address | Alert Count |",
        "| :--- | ---: |",
    ])
    for item in top_ips[:15]:
        lines.append(f"| `{item.get('ip')}` | {item.get('count', 0)} |")

    lines.extend([
        "",
        "## 4. Top Targeted Credentials",
        "",
        "| Username:Password | Attempts |",
        "| :--- | ---: |",
    ])
    for item in top_creds[:15]:
        lines.append(f"| `{item.get('credentials')}` | {item.get('count', 0)} |")

    lines.extend([
        "",
        f"## 5. Correlated Campaigns ({len(campaigns)}) & Behavioral Families ({len(families)})",
        "",
    ])
    for idx, c in enumerate(campaigns[:10], start=1):
        lines.append(f"- **Campaign #{idx}** ({c.get('size', 0)} IPs): `{', '.join(c.get('ips', [])[:8])}` | Reasons: {', '.join(c.get('reasons', []))}")
    for fam in families[:10]:
        lines.append(f"- **Family `{fam.get('label')}`** ({fam.get('size', 0)} IPs): traits `{', '.join(fam.get('common_behavior', []))}`")

    lines.extend([
        "",
        f"## 6. Observed MITRE ATT&CK Techniques ({len(techniques)})",
        "",
        "| Technique ID | Name | Hits |",
        "| :--- | :--- | ---: |",
    ])
    for tech in techniques[:25]:
        lines.append(f"| `{tech.get('techniqueID')}` | {tech.get('comment', '')} | {tech.get('score', 0)} |")

    lines.extend([
        "",
        "## 7. Prioritized Mitigation Recommendations",
        "",
    ])
    for rec, cnt in rec_counter.most_common(12):
        lines.append(f"- ({cnt}x) {rec}")

    return "\n".join(lines) + "\n"


def to_pretty_json(data):
    return json.dumps(data, indent=2, ensure_ascii=False) + "\n"
